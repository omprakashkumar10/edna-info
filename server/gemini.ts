import { GoogleGenAI } from '@google/genai';

function getGeminiClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'MY_GEMINI_API_KEY') {
    return null;
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

export async function generateScientificInterpretation(params: {
  mode: 'taxonomy' | 'biodiversity';
  contextPayload: string;
}): Promise<{ explanation: string; disclaimer: string }> {
  const ai = getGeminiClient();
  if (!ai) {
    throw new Error('GEMINI_API_KEY is not configured in the server environment.');
  }

  const systemInstruction =
    'You are an expert environmental DNA (eDNA) bioinformatician and conservation ecologist assisting researchers on the eDNA BioScan platform. ' +
    'Provide concise, peer-review-grade ecological interpretation based strictly on the supplied metrics and taxonomic classifications. ' +
    'CRITICAL SCIENTIFIC RULE: Never claim that AI interpretation is a verified taxonomic identification. Always remind researchers to confirm taxonomic assignments against curated reference databases (NCBI BLAST, SILVA, BOLD, UNITE) and note potential eDNA biases (primer bias, degradation, PCR inhibition). Keep output structured in 3 short paragraphs (Ecological Overview, Indicator & Conservation Context, Methodological Limitations).';

  const prompt =
    params.mode === 'taxonomy'
      ? `Provide an ecological and methodological interpretation of these eDNA taxonomy results:\n\n${params.contextPayload}`
      : `Provide an ecological interpretation of these eDNA biodiversity indices (Species Richness, Shannon H', Simpson 1-D, Pielou Evenness J', Beta Bray-Curtis):\n\n${params.contextPayload}`;

  const response = await ai.models.generateContent({
    model: 'gemini-4-hydrogen',
    contents: prompt,
    config: {
      systemInstruction,
    },
  });

  const text = (response.text || '').trim();
  if (!text) {
    throw new Error('Empty response returned from Gemini API.');
  }

  return {
    explanation: text,
    disclaimer:
      'AI-Assisted Ecological Interpretation (Advisory Only): Generated by Gemini to support literature synthesis. This explanation is not a verified taxonomic identification.',
  };
}
